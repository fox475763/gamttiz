"""Generate smaller display-only WebP variants, preserving original downloads.
Run from repository root. Only change references when every corresponding image exists.
"""
from pathlib import Path
from PIL import Image, ImageOps
import io, json, re

ROOT = Path.cwd()
ASSET = ROOT / "assets"
PAGES = ("index.html", "products.html", "project.html", "play.html", "combo.html")
pattern = re.compile(r'<img\b[^>]*>', re.I)
src = re.compile(r'\bsrc="(assets/[^"]+\.(?:png|jpg|jpeg|webp))"', re.I)
paths = set()
for page in PAGES:
    for tag in pattern.findall((ROOT / page).read_text(encoding="utf-8")):
        match = src.search(tag)
        if match:
            paths.add(match.group(1))
paths.update(f"assets/keyring-{n:02}.png" for n in range(1, 15))
paths.add("assets/holder.png")
mapping = {}
total_in = total_out = 0

def write_if_changed(path, content):
    if not path.exists() or path.read_bytes() != content:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content)

for rel in sorted(paths):
    source = ROOT / rel
    if not source.is_file() or source.stat().st_size < 50000:
        continue
    # Exclude UI icons, 3D assets and license export originals.
    if any(part in source.parts for part in ("license", "illustrations-3d", "display")):
        continue
    with Image.open(source) as raw:
        if getattr(raw, "n_frames", 1) != 1:
            continue
        image = ImageOps.exif_transpose(raw)
        image = image.convert("RGBA" if "A" in image.getbands() or "transparency" in image.info else "RGB")
        variants = []
        for width in (480, 960, 1440):
            if width > image.width and variants:
                break
            copy = image.copy()
            copy.thumbnail((width, 1700), Image.Resampling.LANCZOS)
            buf = io.BytesIO()
            copy.save(buf, "WEBP", quality=84, method=6, alpha_quality=95)
            data = buf.getvalue()
            if len(data) >= source.stat().st_size * .98:
                continue
            dest = ASSET / "display" / source.relative_to(ASSET).parent / (source.stem + "-" + source.suffix[1:] + "-" + str(copy.width) + ".webp")
            write_if_changed(dest, data)
            if not any(w == copy.width for _, w in variants):
                variants.append((dest.relative_to(ROOT).as_posix(), copy.width))
        if variants:
            mapping[rel] = variants
            total_in += source.stat().st_size
            total_out += (ROOT / variants[-1][0]).stat().st_size

for page in PAGES:
    file = ROOT / page
    raw = file.read_text(encoding="utf-8")
    def convert(m):
        tag = m.group(0)
        match = src.search(tag)
        if not match or match.group(1) not in mapping:
            return tag
        options = mapping[match.group(1)]
        if 'srcset=' in tag and 'data-gtz-display=' not in tag:
            return tag
        tag = re.sub(r'\s+(?:srcset|sizes|data-gtz-display)="[^"]*"', '', tag) if 'data-gtz-display=' in tag else tag
        srcset = ", ".join(f"{path} {width}w" for path, width in options)
        sizes = "(max-width: 600px) 94vw, (max-width: 1000px) 65vw, 720px"
        return tag[:-1] + f' srcset="{srcset}" sizes="{sizes}" data-gtz-display="1">'
    edited = pattern.sub(convert, raw)
    if page in ("index.html", "products.html") and 'src="display-assets.js"' not in edited:
        edited = re.sub(r'(<script\b[^>]*src="(?:app|products)\.js[^"]*"[^>]*>)', r'<script src="display-assets.js" defer></script>\1', edited, count=1)
    if raw != edited:
        write_if_changed(file, edited.encode("utf-8"))

manifest = {name: [[p, w] for p, w in variants] for name, variants in mapping.items()}
write_if_changed(ROOT / "display-assets.js", ("/* Generated by optimize-display-images.py. */\nwindow.GTZDisplayAssets=" + json.dumps(manifest, ensure_ascii=False, separators=(",", ":")) + ";\n").encode())
print(f"Display optimization: {len(mapping)} images, largest display variant {total_out:,} bytes vs {total_in:,} original bytes")
