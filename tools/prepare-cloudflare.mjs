// Package the existing static site without changing GitHub Pages source files.
import fs from 'node:fs';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, '.cloudflare-dist');
const legacy = 'https://fox475763.github.io/gamttiz/';
const configuredURL = process.env.GAMTTIZ_PUBLIC_URL;
let base = '';
if (configuredURL) {
  const url = new URL(configuredURL);
  if (url.protocol !== 'https:' || url.username || url.password || url.pathname !== '/' || url.search || url.hash) {
    throw new Error('GAMTTIZ_PUBLIC_URL must be the HTTPS site origin.');
  }
  base = url.origin + '/';
}

const tracked = execFileSync('git', ['ls-files', '-z'], {cwd:root, encoding:'utf8'}).split('\0').filter(Boolean);
const publicFiles = tracked.filter(file =>
  /^(assets|data|news)\//.test(file) ||
  (!file.includes('/') && /\.(html|css|js|json|svg|webmanifest|xml|txt|ico|png|jpg|jpeg|webp|woff2?)$/i.test(file))
);
if (!publicFiles.includes('index.html') || !publicFiles.includes('member.html') ||
    !publicFiles.includes('data/fry-radar.json') || !publicFiles.includes('news/posts.json')) {
  throw new Error('Required site files are missing.');
}
if (publicFiles.length > 20000) throw new Error('Cloudflare free static asset file limit exceeded.');
if (fs.existsSync(out)) {
  if (!fs.existsSync(path.join(out, '.gamttiz-build'))) throw new Error('Refusing to overwrite an unrecognized output directory.');
  fs.rmSync(out, {recursive:true});
}
fs.mkdirSync(out);
fs.writeFileSync(path.join(out, '.gamttiz-build'), 'Generated by prepare-cloudflare.mjs\n');
let bytes = 0;
for (const file of publicFiles) {
  const source = path.join(root, file);
  const dest = path.join(out, file);
  const stat = fs.lstatSync(source);
  if (!stat.isFile()) throw new Error('Unexpected non-file asset: ' + file);
  if (stat.size > 25 * 1024 * 1024) throw new Error('Asset exceeds Cloudflare free file limit: ' + file);
  fs.mkdirSync(path.dirname(dest), {recursive:true});
  if (file === '404.html') {
    let html = fs.readFileSync(source, 'utf8').replaceAll('href="/gamttiz/', 'href="/');
    if (base) html = html.replaceAll(legacy, base);
    fs.writeFileSync(dest, html);
  } else if (file === 'robots.txt') {
    fs.writeFileSync(dest, 'User-agent: *\nAllow: /\nDisallow: /admin.html\nDisallow: /fry-admin.html\n' +
      (base ? '\nSitemap: ' + base + 'sitemap.xml\n' : ''));
  } else if (base && (/^[^/]+\.html$/.test(file) || file === 'sitemap.xml')) {
    fs.writeFileSync(dest, fs.readFileSync(source,'utf8').replaceAll(legacy, base));
  } else {
    fs.copyFileSync(source, dest);
  }
  bytes += fs.statSync(dest).size;
}
fs.writeFileSync(path.join(out, '_redirects'), '/ /index.html 200\n/gamttiz / 302\n/gamttiz/* /:splat 302\n');
fs.writeFileSync(path.join(out, '.assetsignore'), '.gamttiz-build\n');
console.log(`Cloudflare static package: ${publicFiles.length} files, ${(bytes/1024/1024).toFixed(2)} MiB`);
